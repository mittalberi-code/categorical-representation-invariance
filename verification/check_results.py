"""Offline stdlib audit of retained synthetic data and outputs; does not execute R."""
from pathlib import Path
from collections import Counter
from fractions import Fraction
import csv,json,hashlib,sys
Q=Path(__file__).resolve().parents[1]
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
def readcsv(path):
 with path.open(newline='',encoding='utf-8') as f:return list(csv.DictReader(f))
def eqfreq(rows):return [sum(x==y for y in rows) for x in rows]
manifest=Q/'SHA256SUMS.txt'
if manifest.exists():
 for line in manifest.read_text().splitlines():
  h,p=line.split('  ',1); assert sha(Q/p)==h,p
results=json.loads((Q/'results/python/results_run1.json').read_text())
assert (Q/'results/python/results_run1.json').read_bytes()==(Q/'results/python/results_run2.json').read_bytes()
assert len(results['records'])==562
safe=0;bad=0;flags=0
for r in results['records']:
 rows=r['rows']; truth=eqfreq(rows); exact=Fraction(len(set(map(tuple,rows))),len(rows))
 assert truth==r['oracle_frequencies'] and exact==Fraction(r['oracle_score_exact'])
 assert all(type(v) is str for row in rows for v in row)
 for name,m in r['methods'].items():
  score=sum((Fraction(1,f) for f in m['frequencies']),Fraction())/len(rows)
  assert score==Fraction(m['score_exact'])
  assert m['matches_oracle']==(m['frequencies']==truth)
  assert m['threshold_flag_changes']==((score<=Fraction(1,10))!=(exact<=Fraction(1,10)))
  if name=='delimiter_expression_model':
   c=Counter('|'.join(x) for x in rows)
   assert [c['|'.join(x)] for x in rows]==m['frequencies']
   bad+=not m['matches_oracle'];flags+=m['threshold_flag_changes']
  else:assert m['frequencies']==truth;safe+=1
assert (safe,bad,flags)==(2810,43,2)
allrows=[json.loads(s) for s in (Q/'data/python_dataset_variants.jsonl').read_text().splitlines()]
assert allrows==[{k:r[k] for k in ['id','family','rows']} for r in results['records']]
fixtures=sorted((Q/'data/prepared').glob('*.csv'));assert len(fixtures)==60
assert len({sha(p) for p in fixtures})==54
fixture_truth={}
for p in fixtures:
 with p.open(newline='',encoding='utf-8') as f: rows=list(csv.reader(f))[1:]
 fixture_truth[p.stem]=(rows,eqfreq(rows),Fraction(len(set(map(tuple,rows))),len(rows)))
 assert p.read_bytes()==(Q/'python/inputs/fixtures'/p.name).read_bytes()
 assert sha(p)==results['fixture_sha256'][p.name]
expected=readcsv(Q/'data/expected.csv')
for id,(rows,f,score) in fixture_truth.items():
 e=[r for r in expected if r['id']==id]
 assert [int(r['freq']) for r in e]==f
 assert all(int(r['n'])==len(rows) for r in e)
# Native actual values are retained observations, never regenerated by the Python model.
dataset=readcsv(Q/'results/native/Dataset_Summary.csv');records=readcsv(Q/'results/native/Per_Record_Native_And_Oracle.csv')
assert len(dataset)==120 and len(records)==440
counts={}
for run in ['run-1','run-2']:
 ds=[r for r in dataset if r['run']==run];assert len(ds)==60
 mismatch=changed=record_mismatch=0
 for r in ds:
  rows,f,score=fixture_truth[r['id']];rr=[v for v in records if v['run']==run and v['id']==r['id']]
  assert [int(v['oracle_frequency']) for v in rr]==f
  actual=[int(v['actual_frequency']) for v in rr]
  assert [int(v['row']) for v in rr]==list(range(1,len(rows)+1))
  assert Fraction(int(r['oracle_risk_numerator']),int(r['oracle_risk_denominator']))==score
  assert (r['exact_oracle_privacy_pass']=='TRUE')==(score<=Fraction(1,10))
  assert (r['actual_frequency_agrees']=='TRUE')==(actual==f)
  native=float.fromhex(r['actual_prosecutor_hex'])
  assert native==float(r['actual_prosecutor_17'])
  assert (r['actual_privacy_pass']=='TRUE')==(native<=0.1)
  assert r['status']=='evaluated' and not r['warnings'] and not r['error']
  for risk,ref in [('prosecutor',score),('marketer',score),('journalist',score/100)]:
   value=float.fromhex(r['actual_'+risk+'_hex']);assert value==float(r['actual_'+risk+'_17'])
   assert (r[risk+'_agrees_tolerance_1e12']=='TRUE')==(abs(value-float(ref))<=1e-12)
  mismatch+=actual!=f;changed+=(r['actual_privacy_pass']=='TRUE')!=(score<=Fraction(1,10));record_mismatch+=sum(x!=y for x,y in zip(actual,f))
 assert (mismatch,changed,record_mismatch)==(6,2,28)
 counts[run]={'datasets':60,'record_evaluations':sum(int(r['n']) for r in ds),'frequency_disagreements':mismatch,'flag_changes':changed,'record_mismatches':record_mismatch,'errors':0,'warning_datasets':0}
assert (Q/'results/native/run-1/Native_Raw_Results.rds').read_bytes()==(Q/'results/native/run-2/Native_Raw_Results.rds').read_bytes()
assert (Q/'results/native/run-1/Native_Raw_Results.txt').read_bytes()==(Q/'results/native/run-2/Native_Raw_Results.txt').read_bytes()
u=readcsv(Q/'results/native/Uniqueness_Summary.csv')[0]
assert (int(u['n']),int(u['classes']),int(u['singleton_records']))==(10,2,1)
assert float.fromhex(u['actual_pct_uniques_hex'])==0.5
assert u['agrees_class_denominator']=='TRUE' and u['agrees_record_denominator']=='FALSE'
pin=json.loads((Q/'provenance/SOURCE_PIN.json').read_text());assert sha(Q/'third_party/riskutility_0.2.0.tar.gz')==pin['archive_sha256']
assert sha(Q/'python/inputs/attacker_risk.R')==pin['attacker_source_sha256']
receipt={'status':'pass','python_variants':562,'safe_method_checks':safe,'delimiter_model_disagreements':bad,'prepared_csv_names':60,'prepared_csv_byte_distinct':54,'native_counts':counts,'native_raw_files_byte_identical':True,'native_executed_by_this_checker':False,'interpretation':'Validates retained native exports and raw-byte repeatability; not a fresh native R replication.'}
print(json.dumps(receipt,indent=2))
